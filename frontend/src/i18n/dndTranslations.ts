/**
 * Traduce el nombre de un rasgo o dote, preservando dados o indicadores (ej: "Inspiración Bárdica (d6)" -> "Bardic Inspiration (d6)").
 */
export function translateFeatureName(name: string, lang: Language): string {
  if (!name) return "";
  if (lang === "es") return name;

  const trimmed = name.trim();
  const lower = trimmed.toLowerCase();

  // Coincidencia exacta
  if (FEATURES_MAP[lower]) return FEATURES_MAP[lower];
  if (FEATURES_MAP[stripAccents(lower)]) return FEATURES_MAP[stripAccents(lower)];

  // Extracción de sufijos entre paréntesis ej: " (d6)", " (2d6)", " (CD 15)"
  const parenMatch = trimmed.match(/^(.*?)\s*(\([^)]+\))$/);
  if (parenMatch) {
    const base = parenMatch[1].trim();
    let suffix = parenMatch[2];
    const baseLower = base.toLowerCase();
    const translatedBase = FEATURES_MAP[baseLower] || FEATURES_MAP[stripAccents(baseLower)] || base;
    // Traducir CD -> DC en sufijos
    suffix = suffix.replace(/\bCD\b/g, "DC").replace(/puntos de suerte/gi, "Luck Points");
    return `${translatedBase} ${suffix}`;
  }

  return trimmed;
}

